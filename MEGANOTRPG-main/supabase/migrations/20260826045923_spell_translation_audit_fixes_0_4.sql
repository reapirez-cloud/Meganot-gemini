update public.spell_catalog
set concentration = false,
    notes = case
      when coalesce(notes,'') = '' then 'Не требует концентрации.'
      when notes not ilike '%не требует концентрации%' then notes || ' Не требует концентрации.'
      else notes
    end
where slug = 'glyph-of-warding';

update public.spell_catalog
set effect_summary = 'При провале цель не может использовать Бонусные действия и Реакции и в начале каждого хода бросает 1к10: 1 — не совершает действие и тратит всё движение на перемещение в случайном направлении, определяемом 1к4 (1 — север, 2 — восток, 3 — юг, 4 — запад); 2–6 — не двигается и не действует; 7–8 — не двигается и совершает одну рукопашную атаку по случайному существу в досягаемости, а если целей нет — не действует; 9–10 — действует по своему выбору.'
where slug = 'confusion';
